CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    display_name TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    avatar_file TEXT,
    avatar_rev BIGINT NOT NULL DEFAULT 0,
    about_me TEXT,
    pronouns TEXT,
    custom_status TEXT,
    banner_file TEXT,
    banner_rev BIGINT NOT NULL DEFAULT 0,
    theme_primary BIGINT NOT NULL DEFAULT 2968126,
    theme_secondary BIGINT NOT NULL DEFAULT 1118740,
    nameplate_id TEXT,
    avatar_decoration_id TEXT,
    display_name_style_id TEXT,
    profile_effect_id TEXT,
    profile_frame_id TEXT,
    badge_ids TEXT NOT NULL DEFAULT '[]',
    created_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS profile_widgets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind TEXT NOT NULL,
    title TEXT NOT NULL,
    payload TEXT NOT NULL,
    position BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS profile_connections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind TEXT NOT NULL,
    name TEXT NOT NULL,
    url TEXT NOT NULL,
    position BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS profile_activity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind TEXT NOT NULL,
    title TEXT NOT NULL,
    detail TEXT NOT NULL,
    position BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS profile_wishlist (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    tag TEXT NOT NULL,
    position BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_profile_widgets_user ON profile_widgets(user_id, position);
CREATE INDEX IF NOT EXISTS idx_profile_connections_user ON profile_connections(user_id, position);
CREATE INDEX IF NOT EXISTS idx_profile_activity_user ON profile_activity(user_id, position);
CREATE INDEX IF NOT EXISTS idx_profile_wishlist_user ON profile_wishlist(user_id, position);

CREATE TABLE IF NOT EXISTS sessions (
    token TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    created_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS friend_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_user BIGINT NOT NULL REFERENCES users(id),
    to_user BIGINT NOT NULL REFERENCES users(id),
    created_at BIGINT NOT NULL,
    UNIQUE(from_user, to_user)
);

CREATE TABLE IF NOT EXISTS friendships (
    user_a BIGINT NOT NULL REFERENCES users(id),
    user_b BIGINT NOT NULL REFERENCES users(id),
    created_at BIGINT NOT NULL,
    PRIMARY KEY (user_a, user_b),
    CHECK (user_a < user_b)
);

CREATE TABLE IF NOT EXISTS servers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    owner_id BIGINT NOT NULL REFERENCES users(id),
    created_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS invites (
    code TEXT PRIMARY KEY,
    server_id BIGINT NOT NULL REFERENCES servers(id),
    created_by BIGINT NOT NULL REFERENCES users(id),
    created_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS memberships (
    server_id BIGINT NOT NULL REFERENCES servers(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    nickname TEXT,
    PRIMARY KEY (server_id, user_id)
);

CREATE TABLE IF NOT EXISTS roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    server_id BIGINT NOT NULL REFERENCES servers(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    color BIGINT NOT NULL DEFAULT 0,
    position BIGINT NOT NULL,
    hoist BOOLEAN NOT NULL DEFAULT FALSE,
    permissions BIGINT NOT NULL DEFAULT 0,
    everyone BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_roles_one_everyone ON roles (server_id) WHERE everyone;

CREATE TABLE IF NOT EXISTS member_roles (
    server_id BIGINT NOT NULL REFERENCES servers(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
    PRIMARY KEY (server_id, user_id, role_id)
);

CREATE INDEX IF NOT EXISTS idx_member_roles_role ON member_roles (role_id);

CREATE TABLE IF NOT EXISTS categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    server_id BIGINT NOT NULL REFERENCES servers(id),
    name TEXT NOT NULL,
    position BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS channels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    server_id BIGINT NOT NULL REFERENCES servers(id),
    category_id BIGINT NOT NULL REFERENCES categories(id),
    name TEXT NOT NULL,
    kind TEXT NOT NULL,
    position BIGINT NOT NULL,
    icon TEXT
);

CREATE TABLE IF NOT EXISTS direct_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_a BIGINT NOT NULL REFERENCES users(id),
    user_b BIGINT NOT NULL REFERENCES users(id),
    created_at BIGINT NOT NULL,
    UNIQUE(user_a, user_b),
    CHECK (user_a < user_b)
);

CREATE TABLE IF NOT EXISTS messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id BIGINT REFERENCES channels(id),
    dm_id BIGINT REFERENCES direct_messages(id),
    author_id BIGINT NOT NULL REFERENCES users(id),
    body TEXT NOT NULL,
    reply_to BIGINT REFERENCES messages(id),
    created_at BIGINT NOT NULL,
    edited_at BIGINT,
    CHECK ((channel_id IS NULL) <> (dm_id IS NULL))
);

CREATE TABLE IF NOT EXISTS attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id BIGINT NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
    filename TEXT NOT NULL,
    byte_size BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS mentions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id BIGINT NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id),
    read_at BIGINT
);

CREATE TABLE IF NOT EXISTS board_scenes (
    channel_id BIGINT PRIMARY KEY REFERENCES channels(id) ON DELETE CASCADE,
    revision BIGINT NOT NULL,
    "json" TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS board_assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id BIGINT NOT NULL REFERENCES channels(id) ON DELETE CASCADE,
    filename TEXT NOT NULL,
    byte_size BIGINT NOT NULL,
    content_type TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_messages_channel ON messages(channel_id, id);
CREATE INDEX IF NOT EXISTS idx_messages_dm ON messages(dm_id, id);
CREATE INDEX IF NOT EXISTS idx_messages_reply_to ON messages(reply_to);
CREATE INDEX IF NOT EXISTS idx_mentions_user ON mentions(user_id, read_at);
CREATE INDEX IF NOT EXISTS idx_memberships_user ON memberships(user_id);
CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions(user_id);
CREATE INDEX IF NOT EXISTS idx_board_assets_channel ON board_assets(channel_id);
