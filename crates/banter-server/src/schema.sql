CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    display_name TEXT NOT NULL,
    password_hash TEXT,
    bot BOOLEAN NOT NULL DEFAULT FALSE,
    avatar_file TEXT,
    avatar_rev BIGINT NOT NULL DEFAULT 0,
    about_me TEXT,
    pronouns TEXT,
    custom_status TEXT,
    banner_file TEXT,
    banner_rev BIGINT NOT NULL DEFAULT 0,
    theme_primary BIGINT NOT NULL DEFAULT 2968126,
    theme_secondary BIGINT NOT NULL DEFAULT 1118740,
    nameplate_id TEXT,
    avatar_decoration_id TEXT,
    display_name_style_id TEXT,
    profile_effect_id TEXT,
    profile_frame_id TEXT,
    badge_ids TEXT NOT NULL DEFAULT '[]',
    created_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS profile_widgets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind TEXT NOT NULL,
    title TEXT NOT NULL,
    payload TEXT NOT NULL,
    position BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS profile_connections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind TEXT NOT NULL,
    name TEXT NOT NULL,
    url TEXT NOT NULL,
    position BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS profile_activity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind TEXT NOT NULL,
    title TEXT NOT NULL,
    detail TEXT NOT NULL,
    position BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS profile_wishlist (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    tag TEXT NOT NULL,
    position BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_profile_widgets_user ON profile_widgets(user_id, position);
CREATE INDEX IF NOT EXISTS idx_profile_connections_user ON profile_connections(user_id, position);
CREATE INDEX IF NOT EXISTS idx_profile_activity_user ON profile_activity(user_id, position);
CREATE INDEX IF NOT EXISTS idx_profile_wishlist_user ON profile_wishlist(user_id, position);

CREATE TABLE IF NOT EXISTS sessions (
    token TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    created_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS friend_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_user BIGINT NOT NULL REFERENCES users(id),
    to_user BIGINT NOT NULL REFERENCES users(id),
    created_at BIGINT NOT NULL,
    UNIQUE(from_user, to_user)
);

CREATE TABLE IF NOT EXISTS friendships (
    user_a BIGINT NOT NULL REFERENCES users(id),
    user_b BIGINT NOT NULL REFERENCES users(id),
    created_at BIGINT NOT NULL,
    PRIMARY KEY (user_a, user_b),
    CHECK (user_a < user_b)
);

CREATE TABLE IF NOT EXISTS servers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    owner_id BIGINT NOT NULL REFERENCES users(id),
    created_at BIGINT NOT NULL,
    command_prefix TEXT NOT NULL DEFAULT '/'
);

CREATE TABLE IF NOT EXISTS invites (
    code TEXT PRIMARY KEY,
    server_id BIGINT NOT NULL REFERENCES servers(id),
    created_by BIGINT NOT NULL REFERENCES users(id),
    created_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS memberships (
    server_id BIGINT NOT NULL REFERENCES servers(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    nickname TEXT,
    PRIMARY KEY (server_id, user_id)
);

CREATE TABLE IF NOT EXISTS roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    server_id BIGINT NOT NULL REFERENCES servers(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    color BIGINT NOT NULL DEFAULT 0,
    position BIGINT NOT NULL,
    hoist BOOLEAN NOT NULL DEFAULT FALSE,
    permissions BIGINT NOT NULL DEFAULT 0,
    everyone BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_roles_one_everyone ON roles (server_id) WHERE everyone;

CREATE TABLE IF NOT EXISTS member_roles (
    server_id BIGINT NOT NULL REFERENCES servers(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
    PRIMARY KEY (server_id, user_id, role_id)
);

CREATE INDEX IF NOT EXISTS idx_member_roles_role ON member_roles (role_id);

CREATE TABLE IF NOT EXISTS categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    server_id BIGINT NOT NULL REFERENCES servers(id),
    name TEXT NOT NULL,
    position BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS channels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    server_id BIGINT NOT NULL REFERENCES servers(id),
    category_id BIGINT NOT NULL REFERENCES categories(id),
    name TEXT NOT NULL,
    kind TEXT NOT NULL,
    position BIGINT NOT NULL,
    icon TEXT,
    created_by_plugin TEXT
);

CREATE TABLE IF NOT EXISTS direct_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_a BIGINT NOT NULL REFERENCES users(id),
    user_b BIGINT NOT NULL REFERENCES users(id),
    created_at BIGINT NOT NULL,
    UNIQUE(user_a, user_b),
    CHECK (user_a < user_b)
);

CREATE TABLE IF NOT EXISTS messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id BIGINT REFERENCES channels(id),
    dm_id BIGINT REFERENCES direct_messages(id),
    author_id BIGINT REFERENCES users(id),
    author_kind TEXT NOT NULL DEFAULT 'user',
    plugin_id TEXT,
    body TEXT NOT NULL,
    reply_to BIGINT REFERENCES messages(id),
    created_at BIGINT NOT NULL,
    edited_at BIGINT,
    CHECK ((channel_id IS NULL) <> (dm_id IS NULL))
);

CREATE TABLE IF NOT EXISTS attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id BIGINT NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
    filename TEXT NOT NULL,
    byte_size BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS mentions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id BIGINT NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id),
    read_at BIGINT
);

CREATE TABLE IF NOT EXISTS board_scenes (
    channel_id BIGINT PRIMARY KEY REFERENCES channels(id) ON DELETE CASCADE,
    revision BIGINT NOT NULL,
    "json" TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS board_assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id BIGINT NOT NULL REFERENCES channels(id) ON DELETE CASCADE,
    filename TEXT NOT NULL,
    byte_size BIGINT NOT NULL,
    content_type TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS server_folders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    parent_id BIGINT REFERENCES server_folders(id),
    name TEXT NOT NULL,
    color BIGINT NOT NULL DEFAULT 0,
    position BIGINT NOT NULL,
    collapsed BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX IF NOT EXISTS idx_server_folders_user ON server_folders (user_id);
CREATE INDEX IF NOT EXISTS idx_server_folders_parent ON server_folders (parent_id);

CREATE TABLE IF NOT EXISTS server_folder_memberships (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    server_id BIGINT NOT NULL REFERENCES servers(id) ON DELETE CASCADE,
    folder_id BIGINT REFERENCES server_folders(id),
    position BIGINT NOT NULL,
    PRIMARY KEY (user_id, server_id)
);

CREATE INDEX IF NOT EXISTS idx_server_folder_memberships_folder
    ON server_folder_memberships (user_id, folder_id);

CREATE INDEX IF NOT EXISTS idx_messages_channel ON messages(channel_id, id);
CREATE INDEX IF NOT EXISTS idx_messages_dm ON messages(dm_id, id);
CREATE INDEX IF NOT EXISTS idx_messages_reply_to ON messages(reply_to);
CREATE INDEX IF NOT EXISTS idx_mentions_user ON mentions(user_id, read_at);
CREATE INDEX IF NOT EXISTS idx_memberships_user ON memberships(user_id);
CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions(user_id);
CREATE INDEX IF NOT EXISTS idx_board_assets_channel ON board_assets(channel_id);

CREATE TABLE IF NOT EXISTS bots (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    owner_id BIGINT NOT NULL REFERENCES users(id),
    intents TEXT NOT NULL DEFAULT '[]',
    interactions_url TEXT
);

CREATE TABLE IF NOT EXISTS bot_tokens (
    token TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    created_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS server_bots (
    server_id BIGINT NOT NULL REFERENCES servers(id) ON DELETE CASCADE,
    bot_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    accepted_intents TEXT NOT NULL DEFAULT '[]',
    PRIMARY KEY (server_id, bot_user_id)
);

CREATE TABLE IF NOT EXISTS bot_commands (
    bot_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    body TEXT NOT NULL,
    PRIMARY KEY (bot_user_id, name)
);

CREATE TABLE IF NOT EXISTS server_command_aliases (
    server_id BIGINT NOT NULL REFERENCES servers(id) ON DELETE CASCADE,
    alias TEXT NOT NULL,
    target TEXT NOT NULL,
    PRIMARY KEY (server_id, alias)
);

CREATE INDEX IF NOT EXISTS server_command_aliases_server_idx
    ON server_command_aliases (server_id);

CREATE TABLE IF NOT EXISTS plugins (
    server_id BIGINT NOT NULL REFERENCES servers(id) ON DELETE CASCADE,
    plugin_id TEXT NOT NULL,
    name TEXT NOT NULL,
    version TEXT NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    client TEXT NOT NULL,
    manifest TEXT NOT NULL,
    package_dir TEXT NOT NULL,
    hard_error TEXT,
    PRIMARY KEY (server_id, plugin_id)
);

CREATE TABLE IF NOT EXISTS plugin_storage (
    server_id BIGINT NOT NULL,
    plugin_id TEXT NOT NULL,
    key TEXT NOT NULL,
    value TEXT NOT NULL,
    PRIMARY KEY (server_id, plugin_id, key)
);

CREATE TABLE IF NOT EXISTS plugin_opt_in (
    server_id BIGINT NOT NULL,
    plugin_id TEXT NOT NULL,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    version TEXT NOT NULL,
    PRIMARY KEY (server_id, plugin_id, user_id)
);

CREATE TABLE IF NOT EXISTS plugin_sync (
    server_id BIGINT NOT NULL,
    plugin_id TEXT NOT NULL,
    channel_id BIGINT NOT NULL,
    state TEXT,
    PRIMARY KEY (server_id, plugin_id, channel_id)
);

CREATE TABLE IF NOT EXISTS emote_packs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    slug TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    cover_asset_id BIGINT,
    owner_kind TEXT NOT NULL,
    owner_id BIGINT NOT NULL,
    visibility TEXT NOT NULL,
    created_by BIGINT NOT NULL REFERENCES users(id),
    created_at BIGINT NOT NULL,
    UNIQUE (owner_kind, owner_id, slug),
    CHECK (owner_kind IN ('user', 'server', 'platform')),
    CHECK (visibility IN ('private', 'unlisted', 'public'))
);

CREATE INDEX IF NOT EXISTS idx_emote_packs_owner ON emote_packs (owner_kind, owner_id);
CREATE INDEX IF NOT EXISTS idx_emote_packs_visibility ON emote_packs (visibility);

CREATE TABLE IF NOT EXISTS emote_pack_assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pack_id BIGINT NOT NULL REFERENCES emote_packs(id) ON DELETE CASCADE,
    kind TEXT NOT NULL,
    name TEXT NOT NULL,
    encoding TEXT,
    content_type TEXT NOT NULL,
    byte_size BIGINT NOT NULL,
    width BIGINT,
    height BIGINT,
    duration_ms BIGINT,
    sort_order BIGINT NOT NULL DEFAULT 0,
    created_at BIGINT NOT NULL,
    UNIQUE (pack_id, name),
    CHECK (kind IN ('emote', 'sticker', 'gif')),
    CHECK (encoding IS NULL OR encoding IN ('classic_gif', 'video'))
);

CREATE INDEX IF NOT EXISTS idx_emote_pack_assets_pack ON emote_pack_assets (pack_id, kind, sort_order, id);

CREATE TABLE IF NOT EXISTS emote_pack_subscriptions (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    pack_id BIGINT NOT NULL REFERENCES emote_packs(id) ON DELETE CASCADE,
    created_at BIGINT NOT NULL,
    PRIMARY KEY (user_id, pack_id)
);

CREATE TABLE IF NOT EXISTS server_emote_packs (
    server_id BIGINT NOT NULL REFERENCES servers(id) ON DELETE CASCADE,
    pack_id BIGINT NOT NULL REFERENCES emote_packs(id) ON DELETE CASCADE,
    PRIMARY KEY (server_id, pack_id)
);

CREATE TABLE IF NOT EXISTS message_media (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id BIGINT NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
    asset_id BIGINT NOT NULL REFERENCES emote_pack_assets(id),
    kind TEXT NOT NULL,
    sort_order BIGINT NOT NULL DEFAULT 0,
    CHECK (kind IN ('emote', 'sticker', 'gif'))
);

CREATE INDEX IF NOT EXISTS idx_message_media_message ON message_media (message_id, sort_order, id);

CREATE TABLE IF NOT EXISTS game_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_game_profiles_name_lower ON game_profiles (lower(name));
CREATE INDEX IF NOT EXISTS idx_game_profiles_created_by ON game_profiles (created_by, id);
