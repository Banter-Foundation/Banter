-- Upgrade early Postgres volumes (cutover tip 46917ad) that created `users`
-- without Discord-parity profile columns / tables. Idempotent: safe to re-run
-- before the version is recorded, and skipped once recorded in schema_migrations.

ALTER TABLE users ADD COLUMN IF NOT EXISTS about_me TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS pronouns TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS custom_status TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS banner_file TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS banner_rev BIGINT NOT NULL DEFAULT 0;
ALTER TABLE users ADD COLUMN IF NOT EXISTS theme_primary BIGINT NOT NULL DEFAULT 2968126;
ALTER TABLE users ADD COLUMN IF NOT EXISTS theme_secondary BIGINT NOT NULL DEFAULT 1118740;
ALTER TABLE users ADD COLUMN IF NOT EXISTS nameplate_id TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS avatar_decoration_id TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS display_name_style_id TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS profile_effect_id TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS profile_frame_id TEXT;

CREATE TABLE IF NOT EXISTS profile_widgets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind TEXT NOT NULL,
    title TEXT NOT NULL,
    payload TEXT NOT NULL,
    position BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS profile_connections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind TEXT NOT NULL,
    name TEXT NOT NULL,
    url TEXT NOT NULL,
    position BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_profile_widgets_user ON profile_widgets(user_id, position);
CREATE INDEX IF NOT EXISTS idx_profile_connections_user ON profile_connections(user_id, position);
