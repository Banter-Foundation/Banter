-- Per-user nested server-rail folders with optional hex RGB colors (BA-79).
-- Idempotent for volumes that already ran a tip schema.sql with these tables.

CREATE TABLE IF NOT EXISTS server_folders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    parent_id BIGINT REFERENCES server_folders(id),
    name TEXT NOT NULL,
    color BIGINT NOT NULL DEFAULT 0,
    position BIGINT NOT NULL,
    collapsed BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX IF NOT EXISTS idx_server_folders_user ON server_folders (user_id);
CREATE INDEX IF NOT EXISTS idx_server_folders_parent ON server_folders (parent_id);

CREATE TABLE IF NOT EXISTS server_folder_memberships (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    server_id BIGINT NOT NULL REFERENCES servers(id) ON DELETE CASCADE,
    folder_id BIGINT REFERENCES server_folders(id),
    position BIGINT NOT NULL,
    PRIMARY KEY (user_id, server_id)
);

CREATE INDEX IF NOT EXISTS idx_server_folder_memberships_folder
    ON server_folder_memberships (user_id, folder_id);
