-- Emote Library (BA-83): packs, assets, subscriptions, server offers, message media.

CREATE TABLE IF NOT EXISTS emote_packs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    slug TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    cover_asset_id BIGINT,
    owner_kind TEXT NOT NULL,
    owner_id BIGINT NOT NULL,
    visibility TEXT NOT NULL,
    created_by BIGINT NOT NULL REFERENCES users(id),
    created_at BIGINT NOT NULL,
    UNIQUE (owner_kind, owner_id, slug),
    CHECK (owner_kind IN ('user', 'server', 'platform')),
    CHECK (visibility IN ('private', 'unlisted', 'public'))
);

CREATE INDEX IF NOT EXISTS idx_emote_packs_owner ON emote_packs (owner_kind, owner_id);
CREATE INDEX IF NOT EXISTS idx_emote_packs_visibility ON emote_packs (visibility);

CREATE TABLE IF NOT EXISTS emote_pack_assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pack_id BIGINT NOT NULL REFERENCES emote_packs(id) ON DELETE CASCADE,
    kind TEXT NOT NULL,
    name TEXT NOT NULL,
    encoding TEXT,
    content_type TEXT NOT NULL,
    byte_size BIGINT NOT NULL,
    width BIGINT,
    height BIGINT,
    duration_ms BIGINT,
    sort_order BIGINT NOT NULL DEFAULT 0,
    created_at BIGINT NOT NULL,
    UNIQUE (pack_id, name),
    CHECK (kind IN ('emote', 'sticker', 'gif')),
    CHECK (encoding IS NULL OR encoding IN ('classic_gif', 'video'))
);

CREATE INDEX IF NOT EXISTS idx_emote_pack_assets_pack ON emote_pack_assets (pack_id, kind, sort_order, id);

CREATE TABLE IF NOT EXISTS emote_pack_subscriptions (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    pack_id BIGINT NOT NULL REFERENCES emote_packs(id) ON DELETE CASCADE,
    created_at BIGINT NOT NULL,
    PRIMARY KEY (user_id, pack_id)
);

CREATE TABLE IF NOT EXISTS server_emote_packs (
    server_id BIGINT NOT NULL REFERENCES servers(id) ON DELETE CASCADE,
    pack_id BIGINT NOT NULL REFERENCES emote_packs(id) ON DELETE CASCADE,
    PRIMARY KEY (server_id, pack_id)
);

CREATE TABLE IF NOT EXISTS message_media (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id BIGINT NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
    asset_id BIGINT NOT NULL REFERENCES emote_pack_assets(id),
    kind TEXT NOT NULL,
    sort_order BIGINT NOT NULL DEFAULT 0,
    CHECK (kind IN ('emote', 'sticker', 'gif'))
);

CREATE INDEX IF NOT EXISTS idx_message_media_message ON message_media (message_id, sort_order, id);
