-- Game profiles for Discord-style `<@$GAME_ID>` chat mentions (BA-131).
-- User-created names only; no seed/mock catalog.

CREATE TABLE IF NOT EXISTS game_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_game_profiles_name_lower ON game_profiles (lower(name));
CREATE INDEX IF NOT EXISTS idx_game_profiles_created_by ON game_profiles (created_by, id);
