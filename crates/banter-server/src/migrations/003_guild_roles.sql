-- Guild roles. @everyone is one row per server (position 0). Members gain extra
-- roles through member_roles. permissions 8 is PERM_CREATE_INVITE, so existing
-- members can still create invites after this upgrade.

CREATE TABLE IF NOT EXISTS roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    server_id BIGINT NOT NULL REFERENCES servers(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    color BIGINT NOT NULL DEFAULT 0,
    position BIGINT NOT NULL,
    hoist BOOLEAN NOT NULL DEFAULT FALSE,
    permissions BIGINT NOT NULL DEFAULT 0,
    everyone BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_roles_one_everyone ON roles (server_id) WHERE everyone;

CREATE TABLE IF NOT EXISTS member_roles (
    server_id BIGINT NOT NULL REFERENCES servers(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
    PRIMARY KEY (server_id, user_id, role_id)
);

CREATE INDEX IF NOT EXISTS idx_member_roles_role ON member_roles (role_id);

INSERT INTO roles (server_id, name, color, position, hoist, permissions, everyone)
SELECT s.id, '@everyone', 0, 0, FALSE, 8, TRUE
FROM servers s
WHERE NOT EXISTS (
    SELECT 1 FROM roles r WHERE r.server_id = s.id AND r.everyone
);
