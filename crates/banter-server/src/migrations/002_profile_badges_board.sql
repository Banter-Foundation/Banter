-- BA-62: badges, Activity, and Wishlist on profiles. Idempotent for volumes that
-- already ran schema.sql tip or only 001_profile_customization.

ALTER TABLE users ADD COLUMN IF NOT EXISTS badge_ids TEXT NOT NULL DEFAULT '[]';

CREATE TABLE IF NOT EXISTS profile_activity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind TEXT NOT NULL,
    title TEXT NOT NULL,
    detail TEXT NOT NULL,
    position BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS profile_wishlist (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    tag TEXT NOT NULL,
    position BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_profile_activity_user ON profile_activity(user_id, position);
CREATE INDEX IF NOT EXISTS idx_profile_wishlist_user ON profile_wishlist(user_id, position);
