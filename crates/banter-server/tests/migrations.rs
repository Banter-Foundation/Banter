//! Contracts for versioned Postgres schema upgrades.
//! Written before the migrate runner — an existing early-Postgres volume
//! (CREATE TABLE only, no profile columns) must become usable after Store::open.

use std::path::PathBuf;
use std::sync::atomic::{AtomicU64, Ordering};

use banter_server::{ProfilePatch, Store};

static SCRATCH: AtomicU64 = AtomicU64::new(0);

fn scratch() -> PathBuf {
    let n = SCRATCH.fetch_add(1, Ordering::Relaxed);
    let path = std::env::temp_dir().join(format!("banter-migrate-{}-{n}", std::process::id()));
    let _ = std::fs::remove_dir_all(&path);
    std::fs::create_dir_all(&path).unwrap();
    path
}

fn base_url() -> String {
    std::env::var("BANTER_DATABASE_URL").unwrap_or_else(|_| banter_server::DEFAULT_DATABASE_URL.to_string())
}

fn schema_url(schema: &str) -> String {
    let base = base_url();
    let sep = if base.contains('?') { '&' } else { '?' };
    format!("{base}{sep}options=-csearch_path%3D{schema}")
}

/// Minimal users table matching the first Postgres cutover tip (46917ad),
/// before profile customization columns / tables were restored.
const LEGACY_USERS: &str = r#"
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    display_name TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    avatar_file TEXT,
    avatar_rev BIGINT NOT NULL DEFAULT 0,
    created_at BIGINT NOT NULL
);
"#;

async fn connect_legacy_schema() -> (sqlx::PgPool, String, PathBuf) {
    let n = SCRATCH.fetch_add(1, Ordering::Relaxed);
    let schema = format!("m{}{}", std::process::id(), n);
    let pool = sqlx::PgPool::connect(&base_url())
        .await
        .expect("connect postgres for migration contract");
    sqlx::query(&format!("CREATE SCHEMA {schema}"))
        .execute(&pool)
        .await
        .expect("create schema");
    // Qualify the schema in DDL — pool connections do not share SET search_path.
    let create_users = LEGACY_USERS.replace("CREATE TABLE users", &format!("CREATE TABLE {schema}.users"));
    sqlx::raw_sql(&create_users)
        .execute(&pool)
        .await
        .expect("create legacy users");
    sqlx::query(&format!(
        "INSERT INTO {schema}.users (username, display_name, password_hash, created_at)
         VALUES ('legacy', 'Legacy', 'not-a-real-hash', 1)"
    ))
    .execute(&pool)
    .await
    .expect("seed legacy user");
    let dir = scratch();
    (pool, schema, dir)
}

async fn column_exists(pool: &sqlx::PgPool, schema: &str, column: &str) -> bool {
    let found: Option<i32> = sqlx::query_scalar(
        "SELECT 1 FROM information_schema.columns
         WHERE table_schema = $1 AND table_name = 'users' AND column_name = $2",
    )
    .bind(schema)
    .bind(column)
    .fetch_optional(pool)
    .await
    .expect("column lookup");
    found.is_some()
}

async fn table_exists(pool: &sqlx::PgPool, schema: &str, table: &str) -> bool {
    let found: Option<i32> = sqlx::query_scalar(
        "SELECT 1 FROM information_schema.tables
         WHERE table_schema = $1 AND table_name = $2",
    )
    .bind(schema)
    .bind(table)
    .fetch_optional(pool)
    .await
    .expect("table lookup");
    found.is_some()
}

#[tokio::test]
async fn store_open_upgrades_early_postgres_users_volume() {
    let (pool, schema, dir) = connect_legacy_schema().await;

    assert!(
        !column_exists(&pool, &schema, "about_me").await,
        "precondition: legacy volume lacks about_me"
    );
    assert!(
        !table_exists(&pool, &schema, "profile_widgets").await,
        "precondition: legacy volume lacks profile_widgets"
    );

    let url = schema_url(&schema);
    let store = Store::open(&dir, &url)
        .await
        .expect("Store::open must migrate legacy volume");
    drop(store);

    assert!(column_exists(&pool, &schema, "about_me").await);
    assert!(column_exists(&pool, &schema, "pronouns").await);
    assert!(column_exists(&pool, &schema, "custom_status").await);
    assert!(column_exists(&pool, &schema, "banner_file").await);
    assert!(column_exists(&pool, &schema, "banner_rev").await);
    assert!(column_exists(&pool, &schema, "theme_primary").await);
    assert!(column_exists(&pool, &schema, "theme_secondary").await);
    assert!(column_exists(&pool, &schema, "nameplate_id").await);
    assert!(column_exists(&pool, &schema, "avatar_decoration_id").await);
    assert!(column_exists(&pool, &schema, "display_name_style_id").await);
    assert!(column_exists(&pool, &schema, "profile_effect_id").await);
    assert!(column_exists(&pool, &schema, "profile_frame_id").await);
    assert!(table_exists(&pool, &schema, "profile_widgets").await);
    assert!(table_exists(&pool, &schema, "profile_connections").await);
    assert!(table_exists(&pool, &schema, "schema_migrations").await);

    let versions: Vec<String> = sqlx::query_scalar(&format!(
        "SELECT version FROM {schema}.schema_migrations ORDER BY version"
    ))
    .fetch_all(&pool)
    .await
    .expect("list applied migrations");
    assert!(
        versions.iter().any(|v| v == "001_profile_customization"),
        "expected 001_profile_customization recorded, got {versions:?}"
    );
    assert!(
        versions.iter().any(|v| v == "004_server_folders"),
        "expected 004_server_folders recorded, got {versions:?}"
    );
    assert!(
        table_exists(&pool, &schema, "server_folders").await,
        "expected server_folders after migrate"
    );
    assert!(
        table_exists(&pool, &schema, "server_folder_memberships").await,
        "expected server_folder_memberships after migrate"
    );

    // Profile write must succeed against the upgraded row (proves columns are usable).
    let store = Store::open(&dir, &url)
        .await
        .expect("second open is idempotent");
    let profile = store
        .update_profile(
            1,
            ProfilePatch {
                about_me: Some("hello from migrated volume".into()),
                ..ProfilePatch::default()
            },
        )
        .await
        .expect("update_profile on upgraded users row");
    assert_eq!(profile.about_me.as_deref(), Some("hello from migrated volume"));

    // Re-open again: migration runner must not fail or re-apply.
    let _ = Store::open(&dir, &url)
        .await
        .expect("third open stays idempotent");
    let count: i64 = sqlx::query_scalar(&format!(
        "SELECT COUNT(*) FROM {schema}.schema_migrations WHERE version = '001_profile_customization'"
    ))
    .fetch_one(&pool)
    .await
    .expect("migration row count");
    assert_eq!(count, 1);
}
